#!/usr/bin/env python3
"""
avatar_rotate.py — switch a chat bot's avatar on ONE Discord server according to the day.

Uses `PATCH /guilds/{guild}/members/@me` (per-server avatar), not `PATCH /users/@me`:
it does not touch the bot's global profile and dodges the opaque global-avatar change cooldown.

Choosing the day's "mood", in priority order:
  1. --mood <name>             -> forced by hand (a mood slug or a reference_id)
  2. busy calendar (>= BUSY)   -> a "focus" mood
  3. Monday                    -> a "briefing" mood (week-planning mode)
  4. otherwise                 -> random draw among available moods, avoiding the last 8

Moods come from <base>/moods.json, generated by avatar_build.py from the reference library. To add
a new photo by hand: crop it into <base>/crop/ and add the entry to moods.json.

Idempotent: stores the last applied mood and does not call the API if nothing changed
(use --force to apply anyway). A mood without a matching file is ignored.

Configuration (CLI flag or environment variable):
  --base / AVATAR_BASE              avatars directory: crop/, moods.json, .state.json, history.jsonl
  --guild / DISCORD_GUILD_ID        the server whose per-server avatar is changed
  --token-env (default DISCORD_BOT_TOKEN)
                                    name of the env var holding the bot token
  --env-file / AVATAR_ENV_FILE      optional dotenv file to read the token from if it is not in env
  --events-cmd / AVATAR_EVENTS_CMD  optional shell command printing today's number of calendar
                                    events (an integer); without it the calendar rule is skipped
  AVATAR_TZ                         IANA timezone for "today" and Monday (default: system local)
  DISCORD_USER_AGENT                User-Agent sent to Discord

Example cron (once a day at 07:00):
  0 7 * * *  AVATAR_BASE=/path/to/avatars DISCORD_GUILD_ID=<id> /path/to/avatar_rotate.py
"""

import argparse
import base64
import json
import os
import random
import subprocess
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone

UA = os.environ.get("DISCORD_USER_AGENT", "DiscordBot (https://example.invalid, 1.0)")
BUSY = 5  # events in the day from which the day counts as "busy"
RECENT = 8  # how many recent moods the draw avoids repeating

# Fallback if the manifest is missing: the original hand-made crops.
LEGACY_MOODS = {
    "confident": "confident.png",
    "focus": "focus.png",
    "briefing": "briefing.png",
}


def local_tz():
    name = os.environ.get("AVATAR_TZ")
    if name:
        try:
            from zoneinfo import ZoneInfo
            return ZoneInfo(name)
        except Exception as e:
            print(f"[warn] invalid AVATAR_TZ '{name}' ({e}); using system local time",
                  file=sys.stderr)
    return datetime.now(timezone.utc).astimezone().tzinfo


TZ = local_tz()


def load_manifest(moods_file):
    """mood -> entry. Comes from moods.json, generated from the reference library."""
    try:
        with open(moods_file, encoding="utf-8") as f:
            return json.load(f).get("moods", {})
    except Exception:
        return {m: {"file": a, "reference_id": None, "roles": ["general"]}
                for m, a in LEGACY_MOODS.items()}


def configure(base):
    """(Re)load paths and manifest for an avatars directory. Module-level names stay importable."""
    global BASE, AVATAR_DIR, STATE_FILE, HISTORY_FILE, MOODS_FILE, MANIFEST, MOODS, REF_TO_MOOD
    BASE = base
    AVATAR_DIR = os.path.join(base, "crop")
    STATE_FILE = os.path.join(base, ".state.json")
    HISTORY_FILE = os.path.join(base, "history.jsonl")
    MOODS_FILE = os.path.join(base, "moods.json")
    MANIFEST = load_manifest(MOODS_FILE)
    MOODS = {m: v["file"] for m, v in MANIFEST.items()}
    REF_TO_MOOD = {v["reference_id"]: m for m, v in MANIFEST.items() if v.get("reference_id")}


configure(os.environ.get("AVATAR_BASE", "avatars"))


def read_token(var, env_file):
    token = os.environ.get(var, "")
    if token or not env_file:
        return token
    try:
        with open(env_file) as f:
            for line in f:
                if line.startswith(var + "="):
                    return line.split("=", 1)[1].strip().strip('"')
    except OSError as e:
        print(f"[warn] could not read {env_file} ({e})", file=sys.stderr)
    return ""


def available():
    return {m: f for m, f in MOODS.items() if os.path.exists(os.path.join(AVATAR_DIR, f))}


def events_today(cmd):
    """Number of calendar events today, from a user-supplied command; -1 when unknown."""
    if not cmd:
        return -1
    try:
        out = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=60,
                             check=True).stdout
        return int(out.strip().split()[-1])
    except Exception as e:
        print(f"[warn] could not read the calendar ({e}); continuing without it", file=sys.stderr)
        return -1


def roles(mood):
    return MANIFEST.get(mood, {}).get("roles", ["general"])


def with_role(av, role):
    return [m for m in av if role in roles(m)]


def recent(n=RECENT):
    """Last applied moods, newest first."""
    try:
        with open(HISTORY_FILE, encoding="utf-8") as f:
            lines = [json.loads(l) for l in f if l.strip()]
    except Exception:
        return []
    return [e.get("mood") for e in reversed(lines) if e.get("mood")][:n]


def draw(av, current):
    """Draw while avoiding the current mood and the recent ones — with 40+ photos, repeats are dumb."""
    avoid = set(recent()) | ({current} if current else set())
    pool = [m for m in av if m not in avoid] or [m for m in av if m != current] or list(av)
    return random.choice(pool)


def pick(av, forced=None, current=None, events_cmd=None):
    if forced:
        # accepts both the mood slug ("coffee-chat") and the reference_id ("ref_043")
        target = REF_TO_MOOD.get(forced, forced)
        if target not in av:
            sys.exit(f"mood '{forced}' not available. Available: {', '.join(sorted(av))}")
        return target, "forced on the command line"
    n = events_today(events_cmd)
    if n >= BUSY:
        pool = with_role(av, "focus")
        if pool:
            return draw(pool, current), f"busy calendar ({n} events today)"
    if datetime.now(TZ).weekday() == 0:
        pool = with_role(av, "briefing")
        if pool:
            return draw(pool, current), "Monday — week plan"
    return draw(av, current), f"daily draw ({n if n >= 0 else '?'} events)"


def apply(mood, av, token, guild):
    path = os.path.join(AVATAR_DIR, av[mood])
    data = "data:image/png;base64," + base64.b64encode(open(path, "rb").read()).decode()
    req = urllib.request.Request(
        f"https://discord.com/api/v10/guilds/{guild}/members/@me",
        data=json.dumps({"avatar": data}).encode(),
        headers={"Authorization": f"Bot {token}", "Content-Type": "application/json", "User-Agent": UA},
        method="PATCH")
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.status, json.load(r).get("avatar")


def record(entry):
    """One line per effective change, inside the avatars directory — the agent can read it."""
    try:
        with open(HISTORY_FILE, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception as e:
        print(f"[warn] could not write the history ({e})", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(
        description="Switch a Discord bot's per-server avatar to the mood of the day.")
    ap.add_argument("--base", default=BASE, help="avatars directory (default: $AVATAR_BASE or ./avatars)")
    ap.add_argument("--guild", default=os.environ.get("DISCORD_GUILD_ID"),
                    help="Discord server id ($DISCORD_GUILD_ID)")
    ap.add_argument("--token-env", default="DISCORD_BOT_TOKEN",
                    help="env var holding the bot token (default: DISCORD_BOT_TOKEN)")
    ap.add_argument("--env-file", default=os.environ.get("AVATAR_ENV_FILE"),
                    help="dotenv file to read the token from if not in env ($AVATAR_ENV_FILE)")
    ap.add_argument("--events-cmd", default=os.environ.get("AVATAR_EVENTS_CMD"),
                    help="shell command printing today's event count ($AVATAR_EVENTS_CMD)")
    ap.add_argument("--mood", help="force a mood (slug or reference_id); see --list")
    ap.add_argument("--force", action="store_true", help="reapply even if the mood did not change")
    ap.add_argument("--list", action="store_true", help="list available moods and exit")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--json", action="store_true", help="JSON output (for an agent-facing wrapper)")
    ap.add_argument("--origin", default="cron", help="who asked: cron, agent, user")
    ap.add_argument("--reason", help="overrides the reason text in the log and the history")
    a = ap.parse_args()
    if a.base != BASE:
        configure(a.base)

    av = available()
    if a.list:
        for m, f in sorted(MOODS.items()):
            entry = MANIFEST.get(m, {})
            print(f"  {m:34} {'OK ' if m in av else '-- '} {','.join(entry.get('roles', [])):28} "
                  f"{entry.get('reference_id') or '-':15} {f}")
        return
    if not av:
        sys.exit(f"no images in {AVATAR_DIR}")

    state = {}
    if os.path.exists(STATE_FILE):
        try:
            state = json.load(open(STATE_FILE))
        except Exception:
            pass

    mood, reason = pick(av, a.mood, current=state.get("mood"), events_cmd=a.events_cmd)
    if a.reason:
        reason = a.reason
    stamp = datetime.now(TZ).strftime("%Y-%m-%d %H:%M")
    if state.get("mood") == mood and not a.force and not a.dry_run:
        if a.json:
            print(json.dumps({"changed": False, "mood": mood, "reason": reason,
                              "detail": "already on this mood"}, ensure_ascii=False))
        else:
            print(f"{stamp} | already on '{mood}' ({reason}) — nothing to do")
        return
    if a.dry_run:
        if a.json:
            print(json.dumps({"changed": False, "dry_run": True, "mood": mood,
                              "file": av[mood], "reason": reason}, ensure_ascii=False))
        else:
            print(f"{stamp} | [dry-run] would apply '{mood}' ({av[mood]}) — {reason}")
        return

    if not a.guild:
        sys.exit("no Discord server id — pass --guild or set DISCORD_GUILD_ID")
    token = read_token(a.token_env, a.env_file)
    if not token:
        sys.exit(f"{a.token_env} not found in the environment"
                 + (f" or in {a.env_file}" if a.env_file else ""))
    try:
        code, h = apply(mood, av, token, a.guild)
    except urllib.error.HTTPError as e:
        sys.exit(f"{stamp} | HTTP FAILURE {e.code}: {e.read().decode()[:200]}")
    rid = MANIFEST.get(mood, {}).get("reference_id")
    json.dump({"mood": mood, "at": stamp, "hash": h, "reason": reason, "reference_id": rid},
              open(STATE_FILE, "w"))
    record({"at": stamp, "mood": mood, "file": av[mood], "reference_id": rid,
            "reason": reason, "http": code, "by": a.origin})
    if a.json:
        print(json.dumps({"changed": True, "mood": mood, "file": av[mood],
                          "reason": reason, "at": stamp, "http": code}, ensure_ascii=False))
    else:
        print(f"{stamp} | avatar -> '{mood}' ({av[mood]}) | {reason} | HTTP {code}")


if __name__ == "__main__":
    main()
